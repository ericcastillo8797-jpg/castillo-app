    // En español el mes abreviado lleva punto ("18 sep."); en inglés no ("18 Sep").
    out = out.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\./g, '$1');
